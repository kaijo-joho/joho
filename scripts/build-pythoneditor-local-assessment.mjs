// 固定GAS13の純粋な正規化関数を再利用する。元の判定器や実GASは変更しない。
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import vm from 'node:vm';
const base = new URL('../', import.meta.url);
const original = await readFile(new URL('scripts/pythoneditor-gas/13_python_editor_grader.js', base), 'utf8');
const functions = [...original.matchAll(/^function ([A-Za-z0-9_]+)\([^]*?^}/gm)].map(match => match[0]);
const names = ['normalizeKeywordText_', 'normalizeKeywordWhitespace_', 'compactKeywordText_', 'hasKeywordWhitespace_',
  'parseKeywordString', 'hasSimpleStringLiteralWhitespace_', 'compactCodeOutsideStringLiterals_', 'normalizeSimpleStringLiterals_',
  'parseSimpleAssignment_', 'normalizeExactAssignmentRhs_', 'stripPythonCommentChunk_', 'getEquivalentPlainAssignments_', 'buildExpandedRhsForms_',
  'normalizePowerNotation_', 'stripOuterParens_', 'splitTopLevel_', 'hasTopLevelOperator_', 'canonicalExpressionTerm_', 'multiplicationFactorTerms_',
  'splitTopLevelAddSub_', 'canonicalProductTerm_', 'parseComparisonForOperandEquivalence_', 'reverseComparisonOp_',
  'extractConditionExpressionCandidates_', 'canonicalLimitedBooleanCondition_', 'extractPrintCallSignatures_', 'hasSimpleStringLiteral_',
  'extractFunctionArgumentEquivalenceCalls_', 'isSimpleCommutativeFunctionArgument_', 'groupPyRulesById_', 'groupPyRuleRowsByStep_',
  'buildEquivalentKeywordVariants_', 'buildAugmentedAssignmentVariants_', 'buildReversedComparisonVariants_'];
if (names.some(name => !functions.some(source => source.startsWith('function ' + name + '(')))) throw new Error('旧判定器の関数構造を確認してください。');
const digest = createHash('sha256').update(original).digest('hex');
const helper = '// Generated by scripts/build-pythoneditor-local-assessment.mjs. No question/rubric data.\n' +
  '// Fixed grader source SHA-256: ' + digest + '\nexport const legacyAssessmentHelpers = (function () {\n' + functions.join('\n\n') +
  '\nreturn Object.freeze({' + names.join(',') + '});\n}());\n';
const main = await readFile(new URL('tools/pythoneditor/local-assessment.mjs', base), 'utf8');
const gas = '// Generated local assessment policy compiler. No student code execution or scoring on submission.\n' +
  '// Legacy grader source SHA-256: ' + digest + '\nvar PythonEditorLocalAssessment = (function () {\n' +
  helper.replace('export const legacyAssessmentHelpers', 'const legacyAssessmentHelpers') + '\nconst H = legacyAssessmentHelpers;\n' +
  main.replace(/^import [^\n]+\n/gm, '').replace(/^export /gm, '') +
  '\nreturn Object.freeze({engineVersion:LOCAL_ASSESSMENT_ENGINE,compile:compileAssessment,validatePolicy:validateAssessmentPolicy,' +
  'evaluate:evaluateAssessment,codeHash:assessmentCodeHash,evidenceHash:assessmentEvidenceHash,canonical:assessmentCanonical});\n}());\n';
new vm.Script(gas);
const outputs = [[new URL('tools/pythoneditor/local-assessment-helpers.mjs', base), helper],
  [new URL('scripts/pythoneditor-trial-gas/08_local_assessment.js', base), gas]];
for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error('生成物が一致しません: ' + path.pathname);
  } else { await mkdir(new URL('./', path), { recursive: true }); await writeFile(path, content); }
}
console.log(JSON.stringify({ generated: !process.argv.includes('--check'), checked: process.argv.includes('--check'), legacySourceHash: digest, files: outputs.length }));
