// 公開用の採点器・凍結基準だけを出力する。Drive ID・原本・鍵は出力しない。
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [inputPath, enginePath, dependencyPath] = process.argv.slice(2);
if (!inputPath || !enginePath || !dependencyPath) throw Error('Usage: node scripts/export-html-local-grading.mjs PRIVATE_INPUT.json NORMAL_ENGINE.js ENGINE_NODE_MODULES');
const input = JSON.parse(readFileSync(inputPath, 'utf8'));
const engine = readFileSync(enginePath, 'utf8');
const context = vm.createContext({});
vm.runInContext(engine, context);
const api = context.HtmlNormalConfiguredGrader;
const inEngineRealm = vm.runInContext('text => JSON.parse(text)', context);
if (api?.engineSourceHash !== 'e83fb967aaefe2ec448ee30c415e832587f31598cd10a3ef7824bd0f33a8b22f') throw Error('Unreviewed engine');
const sha = text => createHash('sha256').update(text).digest('hex');
const canonical = value => value === null || typeof value !== 'object' ? JSON.stringify(value) : Array.isArray(value) ? '[' + value.map(canonical).join(',') + ']' : '{' + Object.keys(value).sort().map(k => JSON.stringify(k) + ':' + canonical(value[k])).join(',') + '}';
const snapshots = {};
for (const {snapshot} of input.snapshots) {
  if (sha(canonical(snapshot.body)) !== snapshot.hash) throw Error('Snapshot hash mismatch');
  if (snapshot.body.rubric.targetId !== 'html11-01') api.verifyFrozenRubric(inEngineRealm(JSON.stringify(snapshot)), api.engineVersion, api.engineSourceHash, sha);
  snapshots[snapshot.hash] = snapshot;
}
const fields = ['targetId','templateVersion','templateSha256','rubricVersion','rubricSha256','engineVersion','engineSourceHash'];
const bindings = input.bindings.map(b => {
  const result = Object.fromEntries(fields.map(k => [k, b[k]]));
  const snapshot = snapshots[b.rubricSha256];
  if (!snapshot || snapshot.body.rubric.targetId !== b.targetId || snapshot.body.rubric.version !== b.rubricVersion || snapshot.body.engineVersion !== b.engineVersion || snapshot.body.engineSourceHash !== b.engineSourceHash) throw Error('Binding mismatch');
  return result;
}).sort((a,b) => canonical(a).localeCompare(canonical(b), 'en'));
if (bindings.length !== 40 || Object.keys(snapshots).length !== 14) throw Error('Unexpected archive coverage');
const out = resolve(root, 'tools/htmleditor/grading');
mkdirSync(out, {recursive:true});
// 生成済みGAS採点器の実bytesを変更せずに再利用。実行時の外部通信・HTML実行はしない。
writeFileSync(resolve(out, 'normal-engine.js'), engine);
const catalog = JSON.stringify({schema:1,kind:'html-local-catalog-v1',bindings,snapshots}) + '\n';
writeFileSync(resolve(out, 'catalog.json'), catalog);
const assets = {schema:1,catalog:'grading/catalog.json',catalogSha256:sha(catalog),engine:'grading/normal-engine.js',engineSha256:sha(engine),engineVersion:api.engineVersion,engineSourceHash:api.engineSourceHash};
writeFileSync(resolve(out, '../grading-assets.js'), '// Generated by scripts/export-html-local-grading.mjs. No private identifiers.\nwindow.HtmlLocalGradingAssets = Object.freeze(' + JSON.stringify(assets) + ');\n');
const licenses = ['parse5','entities','css-tree','mdn-data','source-map-js'].map(name => name + '\n' + readFileSync(resolve(dependencyPath,name,'LICENSE'),'utf8')).join('\n\n');
writeFileSync(resolve(out, 'LICENSES.txt'), licenses);
console.log(JSON.stringify({bindings:bindings.length,snapshots:Object.keys(snapshots).length,...assets}));
