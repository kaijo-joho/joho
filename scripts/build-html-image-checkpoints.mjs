// 私有の既存依存から、HTML14の表示用parserを再生成する。GAS・GSSは変更しない。
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dependencies = path.resolve(process.argv[2] || '');
assert(process.argv[2],'Usage: node scripts/build-html-image-checkpoints.mjs ENGINE_NODE_MODULES');
assert.equal(JSON.parse(fs.readFileSync(path.join(dependencies,'parse5/package.json'))).version,'8.0.1');
const {build} = await import(pathToFileURL(path.join(dependencies,'esbuild/lib/main.js')).href);
const result = await build({absWorkingDir:root,entryPoints:['tools/htmleditor/image-checkpoints.mjs'],nodePaths:[dependencies],
  bundle:true,platform:'browser',format:'iife',globalName:'HtmlImageCheckpoints',target:'es2019',charset:'utf8',minify:true,
  legalComments:'inline',metafile:true,write:false,
  banner:{js:'// Generated by scripts/build-html-image-checkpoints.mjs. parse5 8.0.1; see LICENSES.txt.'},
  outfile:'tools/htmleditor/grading/image-checkpoints.js'});
assert(Object.values(result.metafile.outputs).every(o=>o.imports.length===0),'runtime imports');
const bytes = result.outputFiles[0].contents;
fs.writeFileSync(path.join(root,'tools/htmleditor/grading/image-checkpoints.js'),bytes);
const file = path.join(root,'tools/htmleditor/grading-assets.js'), text = fs.readFileSync(file,'utf8');
const match = /Object\.freeze\((\{[^\n]+\})\);/.exec(text);
assert(match,'asset declaration');
const assets = {...JSON.parse(match[1]),imageCheckpoints:'grading/image-checkpoints.js',
  imageCheckpointsSha256:createHash('sha256').update(bytes).digest('hex')};
fs.writeFileSync(file,text.replace(match[1],JSON.stringify(assets)));
console.log(JSON.stringify({bytes:bytes.length,sha256:assets.imageCheckpointsSha256,runtimeImports:0,remoteWrites:false}));
